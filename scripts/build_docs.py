#!/usr/bin/env python3
"""Generate the offline handbook from canonical Markdown; --check is read-only."""
from __future__ import annotations

import argparse
import html
import json
from pathlib import Path
import re
import sys
from urllib.parse import urlsplit, urlunsplit

try:
    from markdown_it import MarkdownIt
except ImportError:
    raise SystemExit("Run with the documentation environment: uv run --locked python scripts/build_docs.py")

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "docs" / "markdown"
PAGES = [
    ("index", "Overview", "The design at a glance and reading paths."),
    ("product", "Product & scope", "Who it serves, what it promises, and where the first release stops."),
    ("pedagogy", "Learning & assessment", "Teaching, proof practice, assistance, and honest evidence."),
    ("architecture", "Architecture", "Local programs, domain boundaries, storage, and trust."),
    ("content", "Content contract", "The proposed package format and execution semantics."),
    ("learner-state", "Learner state", "Attempts, persistence, versioning, backup, and review."),
    ("compiler", "Authoring & compilation", "From reviewed units to reproducible packages."),
    ("experience", "Study experience", "The intended Android flows and recovery states."),
    ("delivery", "Delivery & verification", "Milestones, acceptance scenarios, and risks."),
    ("decisions", "Decision log", "Rationale, tradeoffs, and conditions for revisiting choices."),
]


def slug(text: str) -> str:
    return re.sub(r"[^\w-]+", "-", text.lower(), flags=re.UNICODE).strip("-") or "section"


def render_page(name: str):
    md = MarkdownIt("commonmark", {"html": False}).enable("table")
    text = (SOURCE / f"{name}.md").read_text()
    tokens = md.parse(text)
    headings = []
    used = {}
    plain = []
    for i, token in enumerate(tokens):
        if token.type == "heading_open":
            title = tokens[i + 1].content
            base = slug(title)
            used[base] = used.get(base, 0) + 1
            anchor = base if used[base] == 1 else f"{base}-{used[base]}"
            token.attrSet("id", anchor)
            if token.tag == "h2":
                headings.append((anchor, title))
        if token.type == "inline":
            plain.append(token.content)
        for child in token.children or []:
            if child.type != "link_open":
                continue
            href = child.attrGet("href")
            parts = urlsplit(href)
            if parts.scheme or parts.netloc or not parts.path:
                continue
            target = (SOURCE / parts.path).resolve()
            if target.parent == SOURCE and target.suffix == ".md":
                path = f"{target.stem}.html"
            else:
                # Markdown links are relative to docs/markdown; HTML lives in docs.
                import os
                path = os.path.relpath(target, ROOT / "docs")
            child.attrSet("href", urlunsplit(("", "", path, parts.query, parts.fragment)))
    body = md.renderer.render(tokens, md.options, {})
    body = body.replace("<table>", '<div class="table-scroll" tabindex="0" role="region" aria-label="Scrollable reference table"><table>')
    body = body.replace("</table>", "</table></div>")
    return body, headings, " ".join(plain)


def build():
    outputs = {}
    search = []
    for index, (name, label, description) in enumerate(PAGES):
        body, headings, plain = render_page(name)
        esc = html.escape
        nav = "".join(
            f'<a href="{n}.html"' + (' aria-current="page"' if n == name else "") + f'>{esc(l)}</a>'
            for n, l, _ in PAGES
        )
        toc = "".join(f'<a href="#{anchor}">{esc(title)}</a>' for anchor, title in headings)
        adjacent = []
        if index:
            n, l, _ = PAGES[index - 1]
            adjacent.append(f'<a rel="prev" href="{n}.html"><span>Previous</span>{esc(l)}</a>')
        if index < len(PAGES) - 1:
            n, l, _ = PAGES[index + 1]
            adjacent.append(f'<a rel="next" href="{n}.html"><span>Next</span>{esc(l)}</a>')
        document = f'''<!doctype html>
<!-- Generated by scripts/build_docs.py. Edit docs/markdown/{name}.md. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="description" content="{esc(description)}">
  <meta name="color-scheme" content="light">
  <title>{esc(label)} · Axiora handbook</title>
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="assets/style.css">
  <script defer src="assets/search-index.js"></script>
  <script defer src="assets/search.js"></script>
</head>
<body>
<a class="skip-link" href="#main">Skip to content</a>
<aside class="sidebar" aria-label="Handbook navigation">
  <a class="wordmark" href="index.html">Axiora<span>Mathematics, understood.</span></a>
  <form class="search" role="search" id="search-form" hidden>
    <label for="search-input">Search the handbook</label>
    <div class="search-controls"><input id="search-input" type="search" placeholder="Try ‘proof’ or ‘updates’" autocomplete="off"><button type="submit">Find</button></div>
    <p id="search-status" class="search-status" role="status" aria-live="polite"></p>
    <ul id="search-results" class="search-results" hidden></ul>
  </form>
  <details class="chapter-nav" open>
    <summary>Chapters</summary>
    <nav aria-label="Chapters">{nav}</nav>
  </details>
  <div class="sidebar-foot"><p>Design baseline 0.1<br>16 November 2026</p><a href="../README.md">Repository README</a></div>
</aside>
<div class="reading-pane">
  <header class="page-tools"><a href="index.html">Handbook</a><div><a href="markdown/{name}.md">Markdown source</a><button class="print-button" type="button" id="print-button" hidden>Print chapter</button></div></header>
  <main id="main" tabindex="-1">
    <article>{body}</article>
    <nav class="page-turn" aria-label="Adjacent chapters">{''.join(adjacent)}</nav>
  </main>
  <footer class="page-footer">A proposed learning platform. No application release yet.<br>Human and AI editions share the same source.</footer>
</div>
<aside class="page-outline" aria-label="On this page"><p>On this page</p><nav>{toc}</nav></aside>
</body>
</html>
'''
        outputs[ROOT / "docs" / f"{name}.html"] = document
        search.append({"title": label, "url": f"{name}.html", "description": description, "text": plain})
    outputs[ROOT / "docs" / "assets" / "search-index.js"] = (
        "// Generated by scripts/build_docs.py.\nwindow.AXIORA_SEARCH = "
        + json.dumps(search, ensure_ascii=False).replace("</", "<\\/") + ";\n"
    )
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report stale generated files without writing")
    args = parser.parse_args()
    stale = []
    outputs = build()
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        print("Stale generated files:\n" + "\n".join(stale), file=sys.stderr)
        return 1
    print(f"{'Checked' if args.check else 'Built'} {len(PAGES)} HTML chapters and offline search index.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
